package buildinfo

// The vendored AOP drift check is the safety net for the one place saker copies
// generated code across repositories. These tests build a throwaway saker root
// and a throwaway harness checkout, so they can prove the three states the gate
// must distinguish (consistent, different, absent) without either real checkout.

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// fixtureHarnessPackage is the upstream package clause of the fixture. Only the
// command protocol is generated into a differently named package upstream, and
// the vendored copy renames it (AOPProtoFile.VendoredPackage).
func fixtureHarnessPackage(file AOPProtoFile) string {
	if file.VendoredPackage == "command" {
		return "types"
	}
	return "fixture"
}

// aopProtoFixtureContent mimics a protoc-gen-go file closely enough for the
// normalization rules: the generator header (with version lines), the package
// clause, and the imports the rewrites touch.
func aopProtoFixtureContent(file AOPProtoFile) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by protoc-gen-go. DO NOT EDIT.\n")
	b.WriteString("// versions:\n")
	b.WriteString("// \tprotoc-gen-go v1.36.12\n")
	b.WriteString("// \tprotoc        v7.35.1\n")
	b.WriteString("// source: fixture.proto\n\n")
	fmt.Fprintf(&b, "package %s\n\n", fixtureHarnessPackage(file))
	b.WriteString("import (\n")
	for _, rewrite := range file.Rewrites {
		fmt.Fprintf(&b, "\t_ %q\n", rewrite.Harness)
	}
	b.WriteString("\tprotoreflect \"google.golang.org/protobuf/reflect/protoreflect\"\n")
	b.WriteString(")\n\n")
	fmt.Fprintf(&b, "var Fixture%s = %q\n", strings.ReplaceAll(file.Name, "/", ""), file.Name)
	return []byte(b.String())
}

// writeAOPProtoHarnessFixture writes only the harness side of the pair set.
func writeAOPProtoHarnessFixture(t *testing.T, harnessDir string) {
	t.Helper()
	writeFixtureFile(t, harnessDir, "go.mod", "module example.test/harness\n")
	for _, file := range AOPProtoFiles {
		writeFixtureFile(t, harnessDir, file.HarnessPath, string(aopProtoFixtureContent(file)))
	}
}

// writeAOPProtoVendoredFixture writes only the saker side of the pair set, in
// the exact form a sync from the fixture harness produces.
func writeAOPProtoVendoredFixture(t *testing.T, root string) {
	t.Helper()
	for _, file := range AOPProtoFiles {
		vendored := AOPProtoVendoredContent(aopProtoFixtureContent(file), file)
		writeFixtureFile(t, root, file.VendoredPath, string(vendored))
	}
}

// writeAOPProtoFixture writes both sides consistent with each other.
func writeAOPProtoFixture(t *testing.T, root, harnessDir string) {
	t.Helper()
	writeAOPProtoHarnessFixture(t, harnessDir)
	writeAOPProtoVendoredFixture(t, root)
}

// writeFixtureFile writes one slash-path file below root.
func writeFixtureFile(t *testing.T, root, rel, content string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func readFixtureFile(t *testing.T, root, rel string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

// TestCheckAOPProtoConsistent: a synced tree is ok, every pair is fingerprinted,
// and the result is stable across runs.
func TestCheckAOPProtoConsistent(t *testing.T) {
	root, harnessDir := t.TempDir(), t.TempDir()
	writeAOPProtoFixture(t, root, harnessDir)

	info := CheckAOPProto(root, harnessDir)
	if info.Status != AOPProtoStatusOK {
		t.Fatalf("status = %q, mismatches = %+v", info.Status, info.Mismatches)
	}
	if len(info.Files) != len(AOPProtoFiles) {
		t.Fatalf("files = %d, want %d", len(info.Files), len(AOPProtoFiles))
	}
	for _, file := range info.Files {
		if file.SHA256 == "" || file.SHA256 == "missing" || !file.Matched {
			t.Fatalf("file not fingerprinted/matched: %+v", file)
		}
	}
	if info.SHA256 == "" {
		t.Fatal("empty aggregate fingerprint")
	}
	if info.HarnessCommit != nil {
		t.Fatalf("non-git harness dir reported a commit: %q", *info.HarnessCommit)
	}
	again := CheckAOPProto(root, harnessDir)
	if again.SHA256 != info.SHA256 {
		t.Fatal("fingerprint is not deterministic for an unchanged tree")
	}
	if summary := AOPProtoSummary(again); !strings.Contains(summary, "一致") || !strings.Contains(summary, again.SHA256) {
		t.Fatalf("summary = %q", summary)
	}
}

// TestCheckAOPProtoIgnoresVendoringNoise proves the documented normalization:
// generator toolchain versions, saker's local comment and CRLF checked-out
// files must not read as protocol drift, while a code change must.
func TestCheckAOPProtoIgnoresVendoringNoise(t *testing.T) {
	root, harnessDir := t.TempDir(), t.TempDir()
	writeAOPProtoFixture(t, root, harnessDir)

	path := filepath.Join(root, filepath.FromSlash("internal/aop/pb/chat.pb.go"))
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	noise := strings.ReplaceAll(string(data), "protoc-gen-go v1.36.12", "protoc-gen-go v1.36.6")
	noise = strings.ReplaceAll(noise, "protoc        v7.35.1", "protoc        v5.27.2")
	noise = "// Vendored from cyber-harness; do not edit the wire format here.\n" + noise
	// A Windows checkout may carry CRLF; the comparison normalizes it.
	noise = strings.ReplaceAll(noise, "\n", "\r\n")
	if err := os.WriteFile(path, []byte(noise), 0o644); err != nil {
		t.Fatal(err)
	}
	if info := CheckAOPProto(root, harnessDir); info.Status != AOPProtoStatusOK {
		t.Fatalf("vendoring noise reported as drift: %+v", info.Mismatches)
	}

	// One generated code line changed: that is real drift.
	drift := strings.Replace(string(data), `var Fixtureaopchat = "aop/chat"`, `var Fixtureaopchat = "aop/chat-drift"`, 1)
	if drift == string(data) {
		t.Fatal("fixture replacement did not apply")
	}
	if err := os.WriteFile(path, []byte(drift), 0o644); err != nil {
		t.Fatal(err)
	}
	if info := CheckAOPProto(root, harnessDir); info.Status != AOPProtoStatusMismatch {
		t.Fatalf("code drift not detected: %+v", info)
	}
}

// TestCheckAOPProtoMismatch names the file and the first normalized difference,
// changes the fingerprint, and carries the fix command in the message.
func TestCheckAOPProtoMismatch(t *testing.T) {
	root, harnessDir := t.TempDir(), t.TempDir()
	writeAOPProtoFixture(t, root, harnessDir)
	before := CheckAOPProto(root, harnessDir)

	target := "internal/aop/tool/protocol.pb.go"
	path := filepath.Join(root, filepath.FromSlash(target))
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, append(data, []byte("\nvar DriftAddedByHand = true\n")...), 0o644); err != nil {
		t.Fatal(err)
	}

	info := CheckAOPProto(root, harnessDir)
	if info.Status != AOPProtoStatusMismatch {
		t.Fatalf("status = %q", info.Status)
	}
	if len(info.Mismatches) != 1 {
		t.Fatalf("mismatches = %+v", info.Mismatches)
	}
	mismatch := info.Mismatches[0]
	if mismatch.Path != target || mismatch.HarnessPath != "aop/tool/protocol.pb.go" {
		t.Fatalf("mismatch paths = %+v", mismatch)
	}
	if mismatch.SakerLine == 0 {
		t.Fatalf("extra line not located: %+v", mismatch)
	}
	if info.SHA256 == before.SHA256 {
		t.Fatal("drift did not change the vendored fingerprint")
	}

	message := AOPProtoMismatchMessage(info)
	for _, want := range []string{"不一致", target, "aop/tool/protocol.pb.go", "scripts/sync-aop-protos.ps1", "scripts/sync-aop-protos.sh"} {
		if !strings.Contains(message, want) {
			t.Fatalf("message missing %q:\n%s", want, message)
		}
	}
	t.Logf("gate 失败时的输出：\n%s", message)
}

// TestCheckAOPProtoSkipsWithoutHarness: no harness checkout is a recorded skip
// (never a failure) and still carries the vendored fingerprint.
func TestCheckAOPProtoSkipsWithoutHarness(t *testing.T) {
	root := t.TempDir()
	writeAOPProtoVendoredFixture(t, root)

	info := CheckAOPProto(root, "")
	if info.Status != AOPProtoStatusSkipped {
		t.Fatalf("status = %q", info.Status)
	}
	if info.Reason == nil || !strings.Contains(*info.Reason, "harness 源码") {
		t.Fatalf("reason = %v", info.Reason)
	}
	if info.SHA256 == "" {
		t.Fatal("skip lost the vendored fingerprint")
	}
	if len(info.Mismatches) != 0 {
		t.Fatalf("skip reported mismatches: %+v", info.Mismatches)
	}

	// A configured path that does not exist is the same skip.
	missing := filepath.Join(root, ".build", "harness-src")
	info = CheckAOPProto(root, missing)
	if info.Status != AOPProtoStatusSkipped {
		t.Fatalf("missing dir status = %q", info.Status)
	}
	if info.Reason == nil || !strings.Contains(*info.Reason, "harness 源码缺失") {
		t.Fatalf("missing dir reason = %v", info.Reason)
	}
}

// TestCheckAOPProtoMissingVendoredFile: deleting a copy is drift, not a skip.
func TestCheckAOPProtoMissingVendoredFile(t *testing.T) {
	root, harnessDir := t.TempDir(), t.TempDir()
	writeAOPProtoFixture(t, root, harnessDir)

	target := "internal/aop/operation/protocol.pb.go"
	if err := os.Remove(filepath.Join(root, filepath.FromSlash(target))); err != nil {
		t.Fatal(err)
	}
	info := CheckAOPProto(root, harnessDir)
	if info.Status != AOPProtoStatusMismatch || len(info.Mismatches) != 1 {
		t.Fatalf("status = %q, mismatches = %+v", info.Status, info.Mismatches)
	}
	if mismatch := info.Mismatches[0]; mismatch.Path != target || !strings.Contains(mismatch.Detail, "缺少") {
		t.Fatalf("mismatch = %+v", mismatch)
	}
}

// TestSyncAOPProtoCopiesRewritesAndChecks: the upgrade path copies harness files,
// rewrites only the documented import paths/package, is idempotent, and leaves a
// tree the drift check accepts. A dry run writes nothing.
func TestSyncAOPProtoCopiesRewritesAndChecks(t *testing.T) {
	root, harnessDir := t.TempDir(), t.TempDir()
	writeAOPProtoHarnessFixture(t, harnessDir)

	dry, err := SyncAOPProto(root, harnessDir, true)
	if err != nil {
		t.Fatal(err)
	}
	if !dry.DryRun {
		t.Fatal("dry run not marked")
	}
	for _, file := range dry.Files {
		if !file.Written {
			t.Fatalf("dry run considered %s current in an empty tree", file.Path)
		}
	}
	if _, err := os.Stat(filepath.Join(root, filepath.FromSlash("internal/aop/pb/chat.pb.go"))); !os.IsNotExist(err) {
		t.Fatal("dry run wrote files")
	}

	result, err := SyncAOPProto(root, harnessDir, false)
	if err != nil {
		t.Fatal(err)
	}
	if len(result.Files) != len(AOPProtoFiles) {
		t.Fatalf("files = %d", len(result.Files))
	}
	if info := CheckAOPProto(root, harnessDir); info.Status != AOPProtoStatusOK {
		t.Fatalf("synced tree not consistent: %+v", info.Mismatches)
	}

	guardrail := readFixtureFile(t, root, "internal/aop/guardrail/guardrail.pb.go")
	if !strings.Contains(guardrail, vendoredAOPProto) || !strings.Contains(guardrail, vendoredAOPOperation) {
		t.Fatalf("guardrail imports not rewritten to internal paths:\n%s", guardrail)
	}
	if strings.Contains(guardrail, "github.com/chainreactors/cyber") {
		t.Fatalf("guardrail kept a harness import:\n%s", guardrail)
	}
	traffic := readFixtureFile(t, root, "internal/aop/traffic/protocol.pb.go")
	if !strings.Contains(traffic, vendoredAOPOperation) || strings.Contains(traffic, harnessAOPOperation) {
		t.Fatalf("traffic imports not rewritten:\n%s", traffic)
	}
	command := readFixtureFile(t, root, "internal/aop/command/command.pb.go")
	if !strings.HasPrefix(command, "// Code generated") || !strings.Contains(command, "\npackage command\n") {
		t.Fatalf("command package not renamed:\n%s", command)
	}

	// A second sync is a no-op: the copies are already the exact output.
	again, err := SyncAOPProto(root, harnessDir, false)
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range again.Files {
		if file.Written {
			t.Fatalf("second sync rewrote %s", file.Path)
		}
	}
}

// TestSyncAOPProtoWithoutHarnessIsAnError: syncing has nothing to copy from.
func TestSyncAOPProtoWithoutHarnessIsAnError(t *testing.T) {
	if _, err := SyncAOPProto(t.TempDir(), "", false); err == nil || !strings.Contains(err.Error(), "harness") {
		t.Fatalf("err = %v", err)
	}
	if _, err := SyncAOPProto(t.TempDir(), filepath.Join(t.TempDir(), "absent"), false); err == nil {
		t.Fatal("sync with a missing harness dir succeeded")
	}
}

// TestCollectRecordsAOPProtoField: the build manifest carries the fingerprint and
// status (including the skipped case), so a verification result can name the
// protocol bytes that were built.
func TestCollectRecordsAOPProtoField(t *testing.T) {
	root := initRepo(t)
	harnessDir := t.TempDir()
	writeAOPProtoFixture(t, root, harnessDir)

	manifest, err := Collect(context.Background(), Options{Root: root, HarnessDir: harnessDir})
	if err != nil {
		t.Fatal(err)
	}
	if manifest.AOPProto == nil {
		t.Fatal("manifest has no aop_proto field")
	}
	if manifest.AOPProto.Status != AOPProtoStatusOK {
		t.Fatalf("aop_proto status = %q", manifest.AOPProto.Status)
	}
	if manifest.AOPProto.SHA256 == "" {
		t.Fatal("aop_proto fingerprint empty")
	}
	out := filepath.Join(t.TempDir(), "manifest.json")
	if err := Write(out, manifest); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{`"aop_proto"`, `"sha256"`} {
		if !strings.Contains(string(data), want) {
			t.Fatalf("manifest JSON missing %s:\n%s", want, data)
		}
	}
	if !strings.Contains(string(data), `"status": "ok"`) {
		t.Fatalf("manifest aop_proto status missing:\n%s", data)
	}

	// No harness source: the field is still present, with the skip reason.
	skipped, err := Collect(context.Background(), Options{Root: root})
	if err != nil {
		t.Fatal(err)
	}
	if skipped.AOPProto == nil || skipped.AOPProto.Status != AOPProtoStatusSkipped || skipped.AOPProto.Reason == nil {
		t.Fatalf("skipped aop_proto = %+v", skipped.AOPProto)
	}
	if skipped.AOPProto.SHA256 != manifest.AOPProto.SHA256 {
		t.Fatal("fingerprint depends on harness availability")
	}
}
