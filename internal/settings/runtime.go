// Defaults for the harness's shared `traffic` section, written into the host
// runtime configuration below. The harness default for body_storage is "none"
// (bounded previews only, see cyber-harness pkg/config/traffic.go), which keeps
// the console from showing the exchange's original bytes; Saker switches the
// local scanner's store to disk and keeps the limits bounded.
const (
	defaultTrafficBodyStorage        = "disk"
	defaultTrafficBodyMaxBytes       = int64(8 << 20) // 8 MiB per request/response body
	defaultTrafficBodyRetentionBytes = int64(2 << 30) // 2 GiB retained on disk
)

// MaxTrafficBodyRetentionBytes is the console's upper bound for the scan
// capture-directory retention budget (1 TiB). The harness itself has no upper
// bound; this only keeps a typo from reserving a machine's whole disk as a
// retention target in the console.
const MaxTrafficBodyRetentionBytes = int64(1 << 40)

// TrafficRetention is the effective scan capture-directory retention budget.
//
// It is the harness's node-level `traffic.body_retention_bytes`: one scan
// process keeps its captures in a directory shared by every project on that
// node, so this is an instance/node setting, not a per-project quota. An absent
// or zero value in the operator file means "use the default"; Explicit records
// whether the operator wrote one down.
type TrafficRetention struct {
	Bytes    int64
	Default  int64
	Min      int64
	Max      int64
	Explicit bool
	// Source is the operator-facing sentence the console shows next to the
	// number (where the effective value came from).
	Source string
}

// TrafficRetention reads the effective retention budget from the operator's
// cyber.yaml. A file that cannot be read is not an error here: the console shows
// the default and the settings save reports the real parse error when it tries
// to persist.
func (s *Store) TrafficRetention() TrafficRetention {
	r := TrafficRetention{
		Default: defaultTrafficBodyRetentionBytes,
		Max:     MaxTrafficBodyRetentionBytes,
	}
	bodyMax := defaultTrafficBodyMaxBytes
	if s != nil && s.harness != "" {
		if _, doc, err := s.readDocument(); err == nil {
			if traffic := mapGet(doc, "traffic"); traffic != nil && traffic.Kind == yaml.MappingNode {
				// body_max_bytes=0 is the harness's "use the default" spelling,
				// so only a positive value moves the console's lower bound.
				if n, err := int64Field(traffic, "body_max_bytes"); err == nil && n > 0 {
					bodyMax = n
				}
				if mapGet(traffic, "body_retention_bytes") != nil {
					if n, err := int64Field(traffic, "body_retention_bytes"); err == nil && n > 0 {
						r.Bytes = n
						r.Explicit = true
					}
				}
			}
		}
	}
	if r.Bytes <= 0 {
		r.Bytes = r.Default
	}
	r.Min = 2 * bodyMax
	if r.Explicit {
		r.Source = "操作员 cyber.yaml 顶层 traffic.body_retention_bytes（所有项目共享该 scan 节点的捕获目录）"
	} else {
		r.Source = "默认值（cyber.yaml 未显式设置 traffic.body_retention_bytes；所有项目共享该 scan 节点的捕获目录）"
	}
	return r
}

// ValidateTrafficBodyRetention rejects values the console must not persist.
// 0 means "no explicit value, use the 2 GiB default"; otherwise the harness
// requires two body_max_bytes to fit the retention budget, and the console caps
// the value at 1 TiB.
func (s *Store) ValidateTrafficBodyRetention(bytes int64) error {
	if bytes < 0 {
		return fmt.Errorf("traffic_body_retention_bytes 不能为负数（0 表示使用默认 %d 字节）", defaultTrafficBodyRetentionBytes)
	}
	if bytes == 0 {
		return nil
	}
	min := s.TrafficRetention().Min
	if bytes < min {
		return fmt.Errorf("traffic_body_retention_bytes 至少要为 body_max_bytes 的两倍（当前至少 %d 字节）", min)
	}
	if bytes > MaxTrafficBodyRetentionBytes {
		return fmt.Errorf("traffic_body_retention_bytes 不能超过 1 TiB（%d 字节）", MaxTrafficBodyRetentionBytes)
	}
	return nil
}

// SetTrafficBodyRetention writes the operator's top-level
// traffic.body_retention_bytes and leaves the rest of the traffic section (and
// every other section) untouched. bytes==0 removes the explicit key so the
// default applies again. The runtime host document is regenerated by the caller
// through RuntimeConfig: this setting is read by the scan at process start.
func (s *Store) SetTrafficBodyRetention(bytes int64) error {
	if s.harness == "" {
		return fmt.Errorf("没有 harness 配置路径：设置 SAKER_HARNESS_CONFIG")
	}
	if err := s.ValidateTrafficBodyRetention(bytes); err != nil {
		return err
	}
	s.writeMu.Lock()
	defer s.writeMu.Unlock()
	root, doc, err := s.readDocument()
	if err != nil {
		return err
	}
	traffic := mapGet(doc, "traffic")
	switch {
	case traffic == nil:
		traffic = &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
		mapSet(doc, "traffic", traffic)
	case traffic.Kind != yaml.MappingNode:
		return fmt.Errorf("harness 配置的 traffic 段必须是映射")
	}
	if bytes == 0 {
		mapDelete(traffic, "body_retention_bytes")
	} else {
		mapSet(traffic, "body_retention_bytes", intScalar(bytes))
	}
	// The harness validates the pair at scan startup; fail while editing instead,
	// and never persist a document the next host launch would reject.
	if err := validateTraffic(traffic); err != nil {
		return err
	}
	return s.writeHarnessDocument(root)
}

// writeHarnessDocument rewrites the operator's cyber.yaml from the node graph,
// keeping comments and unknown sections. Indentation matches
// writeHarnessModel's 4 spaces so the settings page and the model save do not
// fight over formatting.
func (s *Store) writeHarnessDocument(root *yaml.Node) error {
	// Every settings save migrates a legacy `extensions:` envelope to flat root
	// sections: the harness reads flat sections now, and leaving the envelope in
	// the operator's file would make the next generated runtime document
	// ambiguous.
	flattenLegacyExtensions(documentRoot(root))
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(4)
	if err := enc.Encode(root); err != nil {
		return fmt.Errorf("编码 %s：%w", s.harness, err)
	}
	if err := enc.Close(); err != nil {
		return fmt.Errorf("编码 %s：%w", s.harness, err)
	}
	return writeFileAtomic(s.harness, buf.Bytes())
}

// runtimeDocument builds the document RuntimeConfig writes. It is split out so
// a settings save can validate the merged configuration (ValidateRuntimeConfig)
// before it persists anything, without materialising a file.
func (s *Store) runtimeDocument() (*yaml.Node, error) {
	// The operator's cyber.yaml is copied through, not filtered down to the
	// shared sections. readDocument keeps every root key: the shared harness
	// options (llm, agent, traffic, …) and the scan-side extension sections
	// (mcp, search, guardrail, jev, …), which the harness now reads as flat
	// top-level sections. This document is the scan process's --config; the
	// Hub gets the projection built by SharedRuntimeConfig, because its strict
	// validator rejects sections it does not declare.
	//
	// Older operator files kept every extension under an `extensions:` envelope.
	// runtimeDocument promotes those entries to root sections on the way in; the
	// operator's file itself is migrated by the next settings write. Only the
	// LLM catalogue is rewritten below; every other section stays verbatim.
	root := &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{{Kind: yaml.MappingNode, Tag: "!!map"}}}
	doc := root.Content[0]
	if s.harness != "" {
		var err error
		root, doc, err = s.readDocument()
		if err != nil {
			return nil, err
		}
		flattenLegacyExtensions(doc)
		// The harness resolves misc.data_dir relative to its configuration
		// file. Moving that file must not move the operator's runtime data.
		if misc := mapGet(doc, "misc"); misc != nil {
			if dataDir := scalar(mapGet(misc, "data_dir")); dataDir != "" && !filepath.IsAbs(dataDir) {
				sourceDir, err := filepath.Abs(filepath.Dir(s.harness))
				if err != nil {
					return nil, err
				}
				setScalar(misc, "data_dir", filepath.Join(sourceDir, dataDir))
			}
		}
	}
	// The runtime sees one endpoint, key and model. Legacy provider catalogues
	// remain in the operator file; they cannot become fallback routes.
	m := s.Effective()
	llm := ensureMapping(doc, "llm")
	mapDelete(llm, "providers")
	mapDelete(llm, "active_profile")
	for _, key := range []string{"pricing", "tier", "api_keys", "max_concurrency", "fallback", "paused"} {
		mapDelete(llm, key)
	}
	setScalar(llm, "provider", m.Provider)
	setScalar(llm, "base_url", m.BaseURL)
	setScalar(llm, "api_key", m.APIKey)
	setScalar(llm, "model", m.Model)
	setIntOrDelete(llm, "context_window", m.ContextWindow)
	setIntOrDelete(llm, "max_tokens", m.MaxTokens)

	// The traffic section is a *shared* harness section: cyber-harness
	// pkg/config/shared_distribution.go projects TrafficOptions into
	// types.DistributeConfig.Traffic (body_storage / body_max_bytes /
	// body_retention_bytes), and pkg/web/service/node_config.go's nodeConfig
	// clones that DistributeConfig (proto.CloneOf) when it distributes the
	// runtime to every scan node. Writing it here is therefore enough for the
	// local scan node, whose harness then records HTTP bodies on disk (the
	// `--observe http` flows already reach the ledger as aop.traffic.Flow).
	//
	// The blank document was read from the operator's cyber.yaml, so an
	// explicit `traffic:` there wins field by field: readDocument preserves the
	// section, and ensureTraffic only fills keys the operator left out instead
	// of overwriting the whole mapping. Deliberately not validating "none" away:
	// an operator may keep the harness's preview-only mode.
	if err := ensureTraffic(doc); err != nil {
		return nil, err
	}
	// The scan process reads this document with the harness's strict parser:
	// shared options plus the sections it declares are accepted, and a misspelt
	// section fails there with the field named. Saker only has to keep the
	// legacy envelope out of the generated document (it was removed from the
	// harness), so a leftover here is a migration defect rather than operator
	// input.
	if err := validateRootDocument(doc); err != nil {
		return nil, err
	}
	return root, nil
}

// ValidateRuntimeConfig applies the checks RuntimeConfig would apply, without
// writing. A settings save calls it before persisting so a legacy top-level
// product section (which the harness rejects at startup) is reported while the
// operator is editing, not at the next boot.
func (s *Store) ValidateRuntimeConfig() error {
	s.writeMu.Lock()
	defer s.writeMu.Unlock()
	_, err := s.runtimeDocument()
	return err
}

// RuntimeConfig materialises the scan-side runtime configuration: the full
// document (shared sections plus the product sections the local scan declares).
// The saved document also carries Saker admission and scheduling metadata, which
// the harness's strict parser must never see, even on an inactive profile.
// A content-addressed path makes Host.Update notice changes to file-only
// settings while a no-op save or admission toggle leaves live sessions alone.
func (s *Store) RuntimeConfig(dir string) (string, error) {
	s.writeMu.Lock()
	defer s.writeMu.Unlock()
	root, err := s.runtimeDocument()
	if err != nil {
		return "", err
	}
	return writeRuntimeDocument(dir, "runtime", root)
}

// SharedRuntimeConfig materialises the Hub-side projection of the same
// document: the shared sections plus the opaque gateway section, with every
// scan-only section dropped. The Hub's strict file validator rejects sections
// it does not declare, and the product sections belong to the scan process, so
// one operator document produces two runtime files.
func (s *Store) SharedRuntimeConfig(dir string) (string, error) {
	s.writeMu.Lock()
	defer s.writeMu.Unlock()
	root, err := s.runtimeDocument()
	if err != nil {
		return "", err
	}
	shared, err := projectSharedDocument(root)
	if err != nil {
		return "", err
	}
	return writeRuntimeDocument(dir, "shared", shared)
}

// writeRuntimeDocument writes one content-addressed runtime file. Two different
// documents (scan and hub) never collide because the digest names the bytes.
func writeRuntimeDocument(dir, prefix string, root *yaml.Node) (string, error) {
	data, err := yaml.Marshal(root)
	if err != nil {
		return "", fmt.Errorf("编码宿主运行配置失败")
	}
	digest := sha256.Sum256(data)
	path, err := filepath.Abs(filepath.Join(dir, fmt.Sprintf("%s-%x.yaml", prefix, digest[:12])))
	if err != nil {
		return "", err
	}
	if err := writeFileAtomic(path, data); err != nil {
		return "", err
	}
	if err := os.Chmod(path, 0o600); err != nil {
		return "", err
	}
	return path, nil
}

func (s *Store) SecretValues() []string {
	values := []string{s.Effective().APIKey}
	// Historic secrets still need redaction, even though they are never selected.
	if root, _, err := s.readDocument(); err == nil {
		var walk func(*yaml.Node)
		walk = func(node *yaml.Node) {
			if node.Kind == yaml.MappingNode {
				for i := 0; i+1 < len(node.Content); i += 2 {
					key, value := node.Content[i].Value, node.Content[i+1]
					if key == "api_key" && value.Kind == yaml.ScalarNode {
						values = append(values, value.Value)
					}
					if key == "api_keys" {
						for _, item := range value.Content {
							if item.Kind == yaml.ScalarNode {
								values = append(values, item.Value)
							}
						}
					}
					walk(value)
				}
			} else {
				for _, item := range node.Content {
					walk(item)
				}
			}
		}
		walk(root)
	}
	return values
}

// ensureTraffic fills the shared harness traffic section with Saker's bounded
// on-disk defaults. Only absent keys are added: the operator's cyber.yaml is the
// authority, and a partially specified section (for example body_storage only)
// must keep every explicit value while the rest falls back to the limits here.
// Values that the harness would reject are reported now, with the section named,
// instead of surfacing later as an opaque scan startup failure.
func ensureTraffic(doc *yaml.Node) error {
	traffic := mapGet(doc, "traffic")
	switch {
	case traffic == nil:
		traffic = &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
		mapSet(doc, "traffic", traffic)
	case traffic.Kind != yaml.MappingNode:
		return fmt.Errorf("harness 配置的 traffic 段必须是映射")
	}
	if mapGet(traffic, "body_storage") == nil {
		setScalar(traffic, "body_storage", defaultTrafficBodyStorage)
	}
	if mapGet(traffic, "body_max_bytes") == nil {
		mapSet(traffic, "body_max_bytes", intScalar(defaultTrafficBodyMaxBytes))
	}
	if mapGet(traffic, "body_retention_bytes") == nil {
		mapSet(traffic, "body_retention_bytes", intScalar(defaultTrafficBodyRetentionBytes))
	}
	return validateTraffic(traffic)
}

// validateTraffic mirrors the checks in cyber-harness pkg/config/traffic.go
// Normalize: body_storage is "none" or "disk", the limits are non-negative, the
// harness's zero-means-default spelling is honoured, and two body_max_bytes must
// fit the retention budget. Duplicating the rule is intentional — the control
// plane writes the file without the harness package available, and the operator
// gets the error while editing settings rather than at the next scan start.
func validateTraffic(traffic *yaml.Node) error {
	storage := strings.ToLower(scalar(mapGet(traffic, "body_storage")))
	if storage == "" {
		storage = "none" // harness Normalize: an empty value defaults to none
	}
	if storage != "none" && storage != "disk" {
		return fmt.Errorf("harness 配置的 traffic.body_storage 必须是 none 或 disk（当前 %q）", storage)
	}
	maxBytes, err := int64Field(traffic, "body_max_bytes")
	if err != nil {
		return err
	}
	retention, err := int64Field(traffic, "body_retention_bytes")
	if err != nil {
		return err
	}
	if maxBytes < 0 || retention < 0 {
		return fmt.Errorf("harness 配置的 traffic 上限不能为负（body_max_bytes=%d, body_retention_bytes=%d）", maxBytes, retention)
	}
	if maxBytes == 0 {
		maxBytes = defaultTrafficBodyMaxBytes
	}
	if retention == 0 {
		retention = defaultTrafficBodyRetentionBytes
	}
	if maxBytes > retention/2 {
		return fmt.Errorf("harness 配置的 traffic 限制不成立：body_max_bytes(%d) 不能超过 body_retention_bytes(%d) 的一半", maxBytes, retention)
	}
	return nil
}

// sharedRootKeys are the root sections cyber-harness (the Hub) declares:
// pkg/config.Option's grouped fields plus the opaque gateway section. The Hub's
// strict file validator rejects every other root key, which is why the scan-side
// document is projected down to this set before the Hub reads it.
var sharedRootKeys = map[string]bool{
	"llm": true, "traffic": true, "agent": true, "inbox": true,
	"node": true, "output": true, "misc": true, "gateway": true,
}

// projectSharedDocument keeps only the sections the Hub declares. Everything
// else belongs to the scan and is read from the full document instead.
func projectSharedDocument(root *yaml.Node) (*yaml.Node, error) {
	doc := documentRoot(root)
	if doc == nil || doc.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("harness 配置根节点必须是映射")
	}
	shared := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	for i := 0; i+1 < len(doc.Content); i += 2 {
		key, value := doc.Content[i], doc.Content[i+1]
		if !sharedRootKeys[key.Value] {
			continue
		}
		shared.Content = append(shared.Content, key, value)
	}
	return &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{shared}}, nil
}

// flattenLegacyExtensions promotes the old `extensions:` envelope to root
// sections in place and removes the envelope. The harness dropped the envelope
// when it moved extension configuration to flat top-level sections; a section
// already present at the root wins over the legacy copy.
func flattenLegacyExtensions(doc *yaml.Node) {
	legacy := mapGet(doc, "extensions")
	if legacy == nil {
		return
	}
	mapDelete(doc, "extensions")
	if legacy.Kind != yaml.MappingNode {
		return
	}
	for i := 0; i+1 < len(legacy.Content); i += 2 {
		key := legacy.Content[i].Value
		if key == "" || mapGet(doc, key) != nil {
			continue
		}
		mapSet(doc, key, legacy.Content[i+1])
	}
}

// sectionNode returns one root section, falling back to the legacy
// `extensions:` envelope when the operator's file still uses it. The read path
// accepts both shapes so an existing cyber.yaml keeps working; the write path
// always produces flat root sections.
func sectionNode(doc *yaml.Node, key string) *yaml.Node {
	if node := mapGet(doc, key); node != nil {
		return node
	}
	return mapGet(mapGet(doc, "extensions"), key)
}

// validateRootDocument rejects a document the harness cannot read. The harness
// now reads flat root sections, so the only structural rule Saker still owns is
// that the removed `extensions:` envelope is gone; every other root section is
// either a shared harness option or an extension section the scan validates at
// startup with the field named.
func validateRootDocument(doc *yaml.Node) error {
	if doc == nil || doc.Kind != yaml.MappingNode {
		return fmt.Errorf("harness 配置根节点必须是映射")
	}
	for i := 0; i+1 < len(doc.Content); i += 2 {
		if doc.Content[i].Value == "extensions" {
			return fmt.Errorf("harness 配置根节点不能有 extensions: 信封；扩展段直接写在顶层（例如 mcp:）")
		}
	}
	return nil
}

func intScalar(value int64) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!int", Value: strconv.FormatInt(value, 10)}
}

func int64Field(node *yaml.Node, key string) (int64, error) {
	value := mapGet(node, key)
	if value == nil || strings.TrimSpace(value.Value) == "" {
		return 0, nil
	}
	n, err := strconv.ParseInt(strings.TrimSpace(value.Value), 10, 64)
	if err != nil {
		return 0, fmt.Errorf("harness 配置的 %s 不是整数：%q", key, value.Value)
	}
	return n, nil
}
