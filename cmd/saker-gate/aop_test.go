package main

// The gate step is a thin policy layer over buildinfo.CheckAOPProto: a
// consistent tree continues, a mismatch fails with the fix command, and a
// missing harness checkout becomes a recorded skip. These tests pin that
// mapping on throwaway directories so the gate's fail/skip contract cannot
// regress while the comparison itself stays covered by the buildinfo tests.

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/kksty/saker/internal/buildinfo"
)

// gateFixtureContent is a minimal generated-file stand-in for the current pair
// set; the buildinfo tests own the comparison semantics.
func gateFixtureContent(file buildinfo.AOPProtoFile) []byte {
	pkg := "fixture"
	if file.VendoredPackage == "command" {
		pkg = "types"
	}
	var b strings.Builder
	b.WriteString("// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: fixture.proto\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import (\n")
	for _, rewrite := range file.Rewrites {
		fmt.Fprintf(&b, "\t_ %q\n", rewrite.Harness)
	}
	b.WriteString(")\n\n")
	fmt.Fprintf(&b, "var Fixture = %q\n", file.Name)
	return []byte(b.String())
}

// writeGateFixture writes a consistent saker root and harness checkout.
func writeGateFixture(t *testing.T, root, harnessDir string) {
	t.Helper()
	write := func(base, rel string, data []byte) {
		t.Helper()
		path := filepath.Join(base, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write(harnessDir, "go.mod", []byte("module example.test/harness\n"))
	for _, file := range buildinfo.AOPProtoFiles {
		content := gateFixtureContent(file)
		write(harnessDir, file.HarnessPath, content)
		write(root, file.VendoredPath, buildinfo.AOPProtoVendoredContent(content, file))
	}
}

func TestRunAOPProtoCheckOK(t *testing.T) {
	root, harnessDir := t.TempDir(), t.TempDir()
	writeGateFixture(t, root, harnessDir)

	info, err := runAOPProtoCheck(root, buildinfo.HarnessSource{Dir: harnessDir, Found: true, Origin: "test"})
	if err != nil {
		t.Fatalf("consistent tree failed: %v", err)
	}
	if info.Status != buildinfo.AOPProtoStatusOK {
		t.Fatalf("status = %q", info.Status)
	}
	if info.SHA256 == "" {
		t.Fatal("empty fingerprint")
	}
}

func TestRunAOPProtoCheckMismatchFailsWithFixHint(t *testing.T) {
	root, harnessDir := t.TempDir(), t.TempDir()
	writeGateFixture(t, root, harnessDir)

	target := filepath.Join(root, filepath.FromSlash("internal/aop/tool/protocol.pb.go"))
	data, err := os.ReadFile(target)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, append(data, []byte("var Drift = true\n")...), 0o644); err != nil {
		t.Fatal(err)
	}

	info, err := runAOPProtoCheck(root, buildinfo.HarnessSource{Dir: harnessDir, Found: true})
	if err == nil {
		t.Fatal("drift did not fail the step")
	}
	if info.Status != buildinfo.AOPProtoStatusMismatch {
		t.Fatalf("status = %q", info.Status)
	}
	for _, want := range []string{"不一致", "internal/aop/tool/protocol.pb.go", "scripts/sync-aop-protos.ps1", "scripts/sync-aop-protos.sh"} {
		if !strings.Contains(err.Error(), want) {
			t.Fatalf("error missing %q:\n%v", want, err)
		}
	}
}

func TestRunAOPProtoCheckMissingHarnessSkips(t *testing.T) {
	root := t.TempDir()
	harnessDir := filepath.Join(root, ".build", "harness-src")

	info, err := runAOPProtoCheck(root, buildinfo.HarnessSource{Dir: harnessDir, Origin: "test"})
	if info == nil || info.Status != buildinfo.AOPProtoStatusSkipped {
		t.Fatalf("info = %+v", info)
	}
	var skip skipStep
	if !errors.As(err, &skip) {
		t.Fatalf("missing harness returned %T %v, want skipStep", err, err)
	}
	if !strings.Contains(skip.reason, "harness 源码缺失") {
		t.Fatalf("skip reason = %q", skip.reason)
	}
}
